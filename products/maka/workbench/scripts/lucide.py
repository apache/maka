# Lucide has no Markdown mark; retain the existing M/down-arrow on its 24-point grid.
DRAWN = {
    "markdown": [("path", {"d": "M2.25 18V6l4.5 6L11.25 6v12M18 6v12m-3-3 3 3 3-3"})],
}

ATTRS = {
    "path": ["d"],
    "circle": ["cx", "cy", "r"],
    "ellipse": ["cx", "cy", "rx", "ry"],
    "rect": ["x", "y", "width", "height", "rx"],
    "line": ["x1", "y1", "x2", "y2"],
    "polyline": ["points"],
    "polygon": ["points"],
}


def element(tag, attrs):
    out = {"tag": tag}
    for name in ATTRS[tag]:
        if name in attrs:
            value = attrs[name]
            out[name] = value if name in ("d", "points") else float(value)
    return out


def main():
    source = pathlib.Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(source).hexdigest() != "064c679194b6ee00999089ecb87176ea8811d2f1a2de26279b57de5cb851972e":
        sys.exit("expected lucide-static 1.61.0 icon-nodes.json")
    nodes = json.loads(source)
    lines = [
        "// Generated by scripts/lucide.py from lucide-static 1.61.0; do not edit.",
        "// Lucide (https://lucide.dev), ISC / Feather MIT; see LICENSE.",
        "// Markdown is a first-party mark retained on the same grid (scripts/lucide.py DRAWN).",
        "export type LucideElement =",
        '  | { tag: "path"; d: string }',
        '  | { tag: "circle"; cx: number; cy: number; r: number }',
        '  | { tag: "ellipse"; cx: number; cy: number; rx: number; ry: number }',
        '  | { tag: "rect"; x: number; y: number; width: number; height: number; rx?: number }',
        '  | { tag: "line"; x1: number; y1: number; x2: number; y2: number }',
        '  | { tag: "polyline" | "polygon"; points: string };',
        "export const lucide = {",
    ]
    for name in sorted([*ICONS, *DRAWN]):
        elements = [element(tag, attrs) for tag, attrs in (DRAWN[name] if name in DRAWN else nodes[name])]
        lines.append(f"  {json.dumps(name)}: {json.dumps(elements)},")
    lines += ["} satisfies Record<string, LucideElement[]>;", ""]
    output = pathlib.Path(__file__).resolve().parent.parent / "app/lucide.ts"
    output.write_text("\n".join(lines))
    repo = pathlib.Path(__file__).resolve().parents[4]
    subprocess.run([str(repo / "node_modules/.bin/biome"), "format", "--write", str(output)], check=True)

main()
