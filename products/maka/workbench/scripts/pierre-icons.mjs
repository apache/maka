import { readFile, writeFile } from 'node:fs/promises';
import { getBuiltInSpriteSheet } from '@pierre/trees';

const rows = [];
for (const [, id, viewBox, paths] of getBuiltInSpriteSheet('standard').matchAll(
  /<symbol id="(file-tree-builtin-[^"]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g,
)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${paths.trim()}</svg>`;
  rows.push(`  '${id}':\n    'data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}',`);
}
if (!rows.length) throw new Error('No standard file icons in the Pierre sprite');
await writeFile(
  new URL('../app/pierreIcons.js', import.meta.url),
  [
    (await readFile(import.meta.url, 'utf8')).split('*/', 1)[0] + '*/',
    '// Generated by scripts/pierre-icons.mjs from @pierre/trees. See LICENSE.',
    "import { createFileTreeIconResolver } from '@pierre/trees';",
    "const { resolveIcon } = createFileTreeIconResolver('standard');",
    'const images = {',
    ...rows,
    '};',
    'export function fileIcon(name) {',
    "  return images[resolveIcon('file-tree-icon-file', name).name];",
    '}',
    '',
  ].join('\n'),
);
