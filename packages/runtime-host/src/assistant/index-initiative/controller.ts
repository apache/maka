import { ASSISTANT_BACKGROUND_SESSION_LABEL } from '@maka/core/session';
import { randomUUID } from 'node:crypto';
import { setTimeout as delay } from 'node:timers/promises';
import { InitiativeStore } from './store.js';
import { awaitingUser } from '../execution-outcome.js';
import { wakeInput, DISCOVERY_TASK, JUDGEMENT_TASK, NOTEBOOK_RULES } from './prompt.js';
import { Notebook, NotebookValidationError } from './notebook.js';
import type { AssistantRunOutcome, RunSegment } from '../run-cost.js';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync, readFileSync, rmSync, chmodSync } from 'node:fs';
import { join } from 'node:path';
import { DiscoveryCoordinator, RECOVERY_ATTEMPT_LIMIT, RECOVERY_LIMIT_MS } from './coordination.js';

export class InitiativeController {
  readonly notebook: Notebook;
  readonly coordinator: DiscoveryCoordinator;
  abort = new AbortController();
  timer: any;
  heartbeat: any;
  owned = false;
  running?: Promise<void>;
  private activeAgent?: any;
  private recovering = false;
  private permit?: string;
  ticking?: Promise<void>;
  enabling = false;
  private bindingResolution?: Promise<void>;
  get bindingReady(): Promise<void> {
    // Share in-flight work and successful resolution, but let the next caller
    // retry a failed startup lookup without restarting the Host.
    return (this.bindingResolution ??= this.resolveBinding().catch((error) => {
      this.bindingResolution = undefined;
      throw error;
    }));
  }
  constructor(
    readonly ctx: any,
    readonly store: InitiativeStore,
    readonly config: any,
  ) {
    const path = join(store.directory, 'notebook.sqlite');
    this.notebook = new Notebook(path);
    this.coordinator = new DiscoveryCoordinator(store, () => this.notebook.sequence());
    this.recovering = this.owesHost();
    this.coordinator.recoveryLanes.broad = () => this.recovering;
    this.coordinator.recoveryState.broad = () => this.store.get()?.recovery;
    chmodSync(path, 0o600);
  }
  refreshNotebook(state = this.store.get()) {
    if (!state) return;
    const context = this.ctx.bot.discoveryContext(state.sessionId);
    this.ready();
    for (const message of context.deliveries) {
      const topicIds = [
        ...new Set(
          message.discoveryIds.flatMap((id: string) => {
            const prepared = this.notebook.event(id);
            return prepared?.kind === 'prepared' ? prepared.payload.topicIds : [];
          }),
        ),
      ];
      // Quick report IDs are generated by QuickDiscoveryController and validated
      // against the Bot inbox before delivery. Never ingest ordinary Bot chat or
      // the report itself: discoveryContext contains only actual delivery receipts.
      const quick = message.discoveryIds.some((id: string) => id.startsWith('quick:'));
      if (!topicIds.length && !quick) continue;
      this.notebook.put(
        `delivery:${message.messageId}`,
        'delivery',
        {
          text: message.text,
          topicIds,
          messageIds: [message.messageId],
          preparedIds: message.discoveryIds,
          transport: 'assistant-bot',
          ...(quick && !topicIds.length ? { origin: 'quick-discovery' } : {}),
        },
        message.at,
      );
    }
    for (const feedback of context.feedback) {
      const replyTo = `delivery:${feedback.messageId}`;
      if (!this.notebook.event(replyTo)) continue;
      const id = `feedback:${JSON.stringify([feedback.id, feedback.messageId])}`;
      // Preserve already imported feedback when the source projection gains fields.
      if (this.notebook.event(id)?.kind === 'feedback') continue;
      this.notebook.recordFeedback({
        id,
        text: feedback.text,
        at: feedback.at,
        replyTo,
      });
    }
  }
  private forwardPrepared(state: any) {
    for (const event of this.notebook.events('prepared')) {
      const id = `${event.id}:reported`;
      if (this.notebook.event(id)) continue;
      // A new user message must be considered before an old recommendation is handed off.
      if (
        event.payload.feedbackRevision !== this.notebook.revision() ||
        this.notebook.pendingFeedback().length
      )
        continue;
      this.ready();
      const accepted = this.ctx.bot.post(state.sessionId, {
        id: event.id,
        type: 'discovery',
        source: state.judgementSession,
        content: event.payload.text,
      });
      if (!accepted) throw Error('Bot did not accept the discovery report');
      if (state.active) this.store.reported(state.active.id);
      this.notebook.put(id, 'reported', { preparedId: event.id, text: event.payload.text });
    }
  }
  start() {
    const acquire = () => {
      const owned = this.store.lease();
      if (owned && !this.owned) {
        // A durable Root may resume before our first tick, including while scheduling is paused.
        this.store.recover(true);
        this.recovering = this.owesHost();
      }
      if (owned) this.coordinator.recover();
      if (!owned && this.owned) this.abort.abort(Error('Initiative ownership lost'));
      this.owned = owned;
    };
    acquire();
    // Observe startup failure; API callers can retry the lookup later.
    void this.bindingReady.catch(() => {});
    this.heartbeat = setInterval(acquire, 10000);
    this.heartbeat.unref?.();
    this.timer = setInterval(() => void this.tick(), this.config.tickMs);
    this.timer.unref?.();
    void this.tick();
  }
  private async resolveBinding() {
    if (this.store.get() || !this.owned) return;
    const matches = (await this.ctx.sessionQuery.list()).filter(
      (s: any) => !s.isArchived && s.labels?.includes('personal-assistant'),
    );
    if (matches.length > 1) throw Error('Multiple assistant conversations found');
    if (!matches.length) return; // First creation is resolved by assistant.bind.
    const session = matches[0];
    if (!session.cwd) throw Error('Assistant conversation has no Host cwd');
    this.ready();
    this.store.bind({ sessionId: session.id, cwd: session.cwd });
  }
  ready() {
    this.abort.signal.throwIfAborted();
    this.store.fence();
  }
  asOwner<T>(s: any, fn: () => T, signal?: AbortSignal): T {
    return this.ctx.agents.withInvocation(
      {
        sessionId: s.sessionId,
        cwd: s.cwd,
        turnId: `initiative-${this.store.owner}`,
        toolCallId: randomUUID(),
        abortSignal: signal ? AbortSignal.any([this.abort.signal, signal]) : this.abort.signal,
      },
      fn,
    );
  }
  tick(): Promise<void> {
    if (this.ticking || this.running || !this.owned || this.abort.signal.aborted)
      return this.ticking ?? Promise.resolve();
    this.ticking = this.dispatch()
      .catch((error) => {
        try {
          this.store.update((s) => {
            if ((s?.enabled || s?.checkRequested) && !s.active) {
              s.lastError = String(error);
              s.nextAt = Date.now() + 30000;
            }
          });
        } catch {
          /* Lease lost. */
        }
      })
      .finally(() => {
        this.ticking = undefined;
      });
    return this.ticking;
  }
  private async restoreExecution() {
    const state = this.store.get();
    const pending = state?.pendingDraft;
    const sessionId =
      pending?.phase === 'discovery' ? state.discoverySession : state?.judgementSession;
    const abandon = () => {
      this.store.update((s) => {
        delete s.recovery;
      });
      this.store.recover(); // Positive absence keeps the existing cadence; it does not replay a check.
      this.recovering = false;
      if (this.permit) this.coordinator.release(this.permit, 'interrupted');
      this.permit = undefined;
      this.coordinator.recover();
    };
    if (!pending || !sessionId) return abandon();
    const sessions = await this.asOwner(state, () => this.ctx.sessionQuery.list());
    if (!sessions.some((session: any) => session.id === sessionId)) {
      this.store.update((s) => {
        delete s.pendingDraft.submission;
      });
      return abandon();
    }
    const agent = await this.asOwner(state, () => this.ctx.agents.resume({ sessionId }));
    const snapshot = await agent.snapshot();
    if (snapshot.root?.kind === 'reserved') return;
    let submission = pending.submission;
    if (!submission) {
      // Pre-upgrade wakes did not persist their message ID. Match the canonical user
      // message for this exact draft, then ask the Host for its durable admission proof.
      const role = pending.phase === 'discovery' ? 'exploration' : 'judgement';
      const directory = join(this.store.directory, 'notebook-wakes', pending.id, role);
      const messages = await agent.transcript();
      const message = [...messages]
        .reverse()
        .find(
          (m: any) =>
            m.type === 'user' &&
            typeof m.text === 'string' &&
            m.text.startsWith('Runtime heartbeat, not a new human request.\nHeartbeat ID: ') &&
            m.text.includes(`\nPhase: ${pending.phase}\n`) &&
            m.text.includes(`完成后把增量操作写入 ${join(directory, 'operations.json')}，格式`),
        );
      if (!message) return abandon();
      let revision = -1; // Missing old feedback snapshots must be repaired, never assumed current.
      try {
        const seed = readFileSync(join(directory, 'notebook.md'), 'utf8');
        const value = JSON.parse(seed.slice(seed.indexOf('\n') + 1)).catalog?.feedbackRevision;
        if (Number.isSafeInteger(value) && value >= 0) revision = value;
      } catch {
        /* Retain the Root and require a fresh draft after it finishes. */
      }
      submission = { messageId: message.id, sessionId, input: message.text, revision };
    }
    const execution = await agent.messageExecution(submission.messageId);
    this.ready();
    if (!execution) {
      // An answer that never comes must not withhold the shared slot from both lanes.
      return this.deferRecovery('the Host did not resolve this submission');
    }
    if (execution.state === 'not_admitted' || execution.state === 'cancelled') {
      if (execution.state === 'cancelled')
        this.store.update((s) => {
          delete s.pendingDraft.submission;
        });
      return abandon();
    }
    if (!['owned', 'pending', 'inbox'].includes(execution.state))
      return this.deferRecovery('the Host returned an unusable admission state');
    const permit = this.permit ?? this.coordinator.acquire('broad');
    if (!permit) return;
    this.coordinator.assertActive(permit);
    const current = this.store.update((s) => {
      if (s.pendingDraft?.id !== pending.id) throw Error('Heartbeat ownership changed');
      s.active ??= { id: pending.id, startedAt: Date.now(), phase: pending.phase };
      s.pendingDraft.submission = submission;
      delete s.recovery;
    });
    this.recovering = false;
    this.launch(agent, current, permit);
  }
  /** An unfinished cycle whose admission the Host has not resolved. A recovery that was
   * already given up keeps its saved submission without withholding the shared slot. */
  private owesHost() {
    const s = this.store.get();
    return !s?.recovery?.exceededAt && !!(s?.active || s?.pendingDraft?.submission);
  }
  /** Count one unresolved admission. Past the bound the lane stops withholding the slot,
   * keeps the saved submission, and reports the degradation instead of guessing. */
  private deferRecovery(reason: string) {
    const recovery = this.store.update((s) => {
      const now = Date.now();
      const before = s.recovery;
      const since = before?.since ?? now;
      const attempts = (before?.attempts ?? 0) + 1;
      const exceeded =
        !!before?.exceededAt ||
        now - since >= RECOVERY_LIMIT_MS ||
        attempts >= RECOVERY_ATTEMPT_LIMIT;
      s.recovery = exceeded
        ? { since, attempts, exceededAt: before?.exceededAt ?? now, reason }
        : { since, attempts };
      return s.recovery;
    });
    if (!recovery.exceededAt) return;
    this.store.update((s) => {
      s.active = null;
      s.lastError = `Discovery wake is not confirmed yet: ${reason}`;
      // Keep the failed cadence: the next scheduled check reattaches the saved submission
      // instead of submitting it again.
      s.nextAt = Date.now() + s.intervalMs;
    });
    this.recovering = false;
    if (this.permit) this.coordinator.release(this.permit, 'interrupted');
    this.permit = undefined;
    this.coordinator.recover();
  }
  private launch(agent: any, current: any, permit: string) {
    this.permit = permit;
    this.running = this.run(agent, current).finally(() => {
      this.running = undefined;
      const state = this.store.get();
      this.recovering = this.owesHost();
      // Unknown or interrupted execution still owns the original memory interval.
      if (this.recovering) return;
      this.permit = undefined;
      this.coordinator.release(
        permit,
        state?.lastRun?.id === current.active.id && state.lastRun.outcome !== 'error'
          ? 'completed'
          : 'interrupted',
      );
    });
  }
  async dispatch() {
    if (this.running) return;
    if (this.recovering) {
      await this.restoreExecution();
      if (this.recovering || this.running) return;
    }
    const s = this.store.get();
    if ((!s?.enabled && !s?.checkRequested) || s.active || s.nextAt > Date.now()) {
      this.coordinator.withdraw('broad');
      return;
    }
    const permit = this.coordinator.acquire('broad');
    if (!permit) return;
    let admitted = false;
    try {
      const agent = await this.worker(
        s,
        s.pendingDraft?.phase ??
          (s.pendingJudgement || s.candidateReport ? 'judgement' : 'discovery'),
      );
      const snapshot = await agent.snapshot();
      if (
        snapshot.root?.kind === 'reserved' ||
        snapshot?.agent?.status === 'running' ||
        awaitingUser(snapshot)
      )
        return;
      this.ready();
      this.coordinator.assertActive(permit);
      const current = this.store.claim();
      if (!current?.active) return;
      admitted = true;
      this.launch(agent, current, permit);
    } finally {
      if (!admitted) this.coordinator.release(permit);
    }
  }
  private async worker(s: any, phase: 'discovery' | 'judgement') {
    return this.asOwner(s, async () => {
      const field = phase === 'discovery' ? 'discoverySession' : 'judgementSession';
      // Pin even legacy admission before the first await: configuration must not
      // switch modes between selecting the worker and claiming the cycle.
      const context = this.store.prepareContext(s.contextMode ?? 'legacy');
      const mode = context.mode;
      const key = mode === 'scoped' ? context.id : 'legacy';
      const label = `assistant-${phase}:${s.sessionId}${mode === 'scoped' ? ':' + key : ''}`;
      const sessions = await this.ctx.sessionQuery.list();
      const matches = sessions.filter(
        (item: any) => !item.isArchived && item.labels?.includes(label),
      );
      const previous = this.store.worker(s[field]);
      const bound =
        previous && previous.mode === mode && previous.contextKey === key
          ? sessions.find((item: any) => item.id === s[field] && !item.isArchived)
          : undefined;
      if (!bound && matches.length > 1) throw Error(`Multiple ${phase} workers found`);
      const sessionId =
        bound?.id ??
        matches[0]?.id ??
        (
          await this.ctx.agents.create({
            background: true,
            name: phase === 'discovery' ? '个人助手 · 主动发现' : '个人助手 · 发现判断',
            labels: [label, ASSISTANT_BACKGROUND_SESSION_LABEL],
          })
        ).sessionId;
      // Keep old worker roles durable so replacing a worker never restores write tools.
      if (previous)
        this.store.bindWorker(s[field], previous.role, previous.mode, previous.contextKey);
      this.store.bindWorker(sessionId, phase, mode, key);
      this.store.update((current) => {
        if (current[field] !== sessionId && current.promptVersions)
          delete current.promptVersions[phase === 'discovery' ? 'exploration' : 'judgement'];
        current[field] = sessionId;
      });
      return this.ctx.agents.resume({ sessionId });
    });
  }
  private async execute(agent: any, state: any) {
    this.ready();
    this.activeAgent = agent;
    await this.refreshNotebook(state);
    const role = state.active.phase === 'discovery' ? 'exploration' : 'judgement';
    // Persist the operation before running the model. A failed or interrupted draft
    // must resume in its original worker, with its original output still available.
    const pending = state.pendingDraft ?? { id: state.active.id, phase: state.active.phase };
    if (pending.phase !== state.active.phase) throw Error('Pending draft phase mismatch');
    this.store.update((s) => {
      s.pendingDraft = pending;
    });
    const operationId = `${pending.id}:${role}`;
    const directory = join(this.store.directory, 'notebook-wakes', pending.id, role);
    const viewPath = join(directory, 'notebook.md');
    const outputPath = join(directory, 'operations.json');
    const version = createHash('sha256')
      .update((role === 'exploration' ? DISCOVERY_TASK : JUDGEMENT_TASK) + '\n' + NOTEBOOK_RULES)
      .digest('hex');
    let repair =
      pending.error ?? (state.pendingDraft ? '上次执行中断，尚无成功提交记录。' : undefined);
    // A committed operation can survive a crash or a failed Bot handoff. Retry its
    // delivery using the existing message IDs, without asking the model to rewrite it.
    while (!this.notebook.event(operationId)) {
      this.ready();
      await this.refreshNotebook(state);
      let submission = this.store.get().pendingDraft.submission;
      if (!submission) {
        mkdirSync(directory, { recursive: true, mode: 0o700 });
        writeFileSync(viewPath, this.notebook.seed(this.coordinator.previous()), { mode: 0o600 });
        let input = wakeInput({
          role,
          now: new Date().toISOString(),
          viewPath,
          outputPath,
          first: this.store.get().promptVersions?.[role] !== version,
        });
        if (repair)
          input += `\n上次结果未提交：${repair}\n整份操作未写入记事本，其中的消息未交给 Bot，也不在待发送队列。读取原结果文件（若存在）和更新后的记事本，修正后重交；保留仍值得交流的内容，不要因为已经写过文案就当成已安排。feedbackDecisions 只引用记事本“用户反馈”中的 ID，没有待整理反馈就留空。`;
        if (role === 'judgement' && state.candidateReport?.path)
          input += `\n升级前保留的历史报告：${state.candidateReport.path}。它是参考材料，不是指定候选或当前指令。`;
        const messageId = randomUUID();
        submission = {
          messageId,
          sessionId: agent.sessionId,
          revision: this.notebook.revision(),
          version,
          input: `Runtime heartbeat, not a new human request.\nHeartbeat ID: ${state.active.id}\nSubmission attempt: ${messageId}\nPhase: ${state.active.phase}\n${input}`,
        };
        this.store.update((s) => {
          s.pendingDraft.submission = submission;
        });
      }
      let execution = await agent.messageExecution(submission.messageId);
      if (!execution) throw Error('Heartbeat admission is not yet known');
      if (execution.state === 'not_admitted') {
        const admitted = await agent.followup(submission.input, {
          messageId: submission.messageId,
        });
        if (!['turn_started', 'followup'].includes(admitted?.disposition))
          throw Error('Host rejected proactive wake');
      }
      for (;;) {
        this.ready();
        execution = await agent.messageExecution(submission.messageId);
        if (execution?.state === 'owned') break;
        if (execution?.state === 'cancelled') {
          this.store.update((s) => {
            delete s.pendingDraft.submission;
          });
          throw Error('Heartbeat wake was cancelled');
        }
        await delay(25, undefined, { signal: this.abort.signal });
      }
      for (;;) {
        let failure: unknown;
        try {
          await agent.whenIdle(this.abort.signal);
        } catch (error) {
          failure = error;
        }
        this.ready();
        const snapshot = await agent.snapshot();
        if (awaitingUser(snapshot)) {
          if (failure) throw failure;
          await delay(1000, undefined, { signal: this.abort.signal });
          continue;
        }
        const terminalFailure = ['failed', 'aborted', 'blocked'].includes(snapshot?.agent?.status);
        if (failure && !terminalFailure) throw failure;
        this.store.update((s) => {
          delete s.pendingDraft.submission;
        });
        if (failure) throw failure;
        if (terminalFailure)
          throw Error(`Heartbeat ended with ${snapshot.agent.status}; inspect before resuming`);
        break;
      }
      if (submission.version)
        this.store.update((s) => {
          (s.promptVersions ??= {})[role] = submission.version;
        });
      await this.refreshNotebook(state);
      // I/O / provider failures remain execution failures. Only fixable draft errors
      // go back to the same agent immediately; never silently drop an invalid field.
      const raw = readFileSync(outputPath, 'utf8');
      try {
        this.notebook.commitDraft({
          role,
          operationId,
          expectedFeedbackRevision: submission.revision,
          draft: JSON.parse(raw),
        });
      } catch (error) {
        if (!(error instanceof SyntaxError || error instanceof NotebookValidationError))
          throw error;
        repair = String(error);
        this.store.update((s) => {
          s.pendingDraft.error = repair;
          this.store.log('draft-rejected', { operationId, error: repair });
        });
      }
    }
    if (role === 'judgement') this.forwardPrepared(state);
    // Only remove the files after commit and handoff. The durable operation marker
    // remains available if shutdown happens before the scheduler finishes this phase.
    rmSync(directory, { recursive: true, force: true });
  }

  async run(agent: any, state: any) {
    const id = state.active.id;
    const startedAt = state.active.startedAt ?? Date.now();
    // Each Session the heartbeat drives and the window it was driven in, so the
    // run's cost can be read back from the Usage ledger afterwards (#6309).
    const segments: RunSegment[] = [];
    const measured = async (worker: any, work: () => Promise<void>) => {
      const from = Date.now();
      try {
        await work();
      } finally {
        segments.push({ sessionId: worker.sessionId, from, to: Date.now() });
      }
    };
    let outcome: AssistantRunOutcome = 'failed';
    this.activeAgent = agent;
    try {
      await measured(agent, () => this.execute(agent, state));
      if (state.active.phase === 'discovery') {
        const next = this.store.update((s) => {
          if (s.active?.id !== id) throw Error('Heartbeat ownership changed');
          s.pendingJudgement = true;
          delete s.pendingDraft;
          s.active.phase = 'judgement';
        });
        const judge = await this.worker(next, 'judgement');
        const snapshot = await judge.snapshot();
        if (snapshot?.agent?.status === 'running' || awaitingUser(snapshot))
          throw Error('Judgement worker is busy or awaiting user input; notebook retained');
        await measured(judge, () => this.execute(judge, this.store.get()));
      }
      // The signal the run's `lastRun` outcome is derived from: the Bot accepted a report.
      outcome = this.store.get()?.active?.reported ? 'reported' : 'no_report';
      this.store.finish(id);
    } catch (e) {
      try {
        this.store.fence();
        if (this.store.get()?.active?.id === id) {
          const message = String(e);
          this.store.update((s) => {
            if (s.pendingDraft && !s.pendingDraft.error) s.pendingDraft.error = message;
          });
          if (this.abort.signal.aborted || this.store.get()?.pendingDraft?.submission) {
            // Preserve the activation until the Host proves the original execution settled.
            this.store.update((s) => {
              s.lastError = message;
            });
          } else this.store.finish(id, message);
        }
      } catch {
        /* A newer owner fences writes and cancellation. */
      }
    } finally {
      this.activeAgent = undefined;
      // Observation only: the ledger swallows its own failures and nothing reads it back.
      await this.ctx.runCost?.record({
        kind: 'discovery',
        runId: id,
        startedAt,
        endedAt: Date.now(),
        outcome,
        segments,
      });
    }
  }
  async enable(input: any, call: any) {
    await this.bindingReady;
    this.ready();
    if (this.enabling) throw Error('Initiative configuration is already in progress');
    this.enabling = true;
    try {
      const old = this.store.get();
      if (!old || old.sessionId !== call.sessionId)
        throw Error('Only the assistant conversation may configure heartbeats');
      if (old?.enabled && input.intervalMinutes === undefined) return old;
      const s = this.store.configure(
        { sessionId: old.sessionId, cwd: old.cwd },
        input.intervalMinutes === undefined
          ? (old?.intervalMs ?? 1800000)
          : input.intervalMinutes * 60000,
      );
      void this.tick();
      return s;
    } finally {
      this.enabling = false;
    }
  }
  async configure(
    input: { intervalMinutes?: number; contextMode?: 'legacy' | 'scoped' },
    call: any,
  ) {
    await this.bindingReady;
    this.ready();
    const old = this.store.get();
    if (!old || old.sessionId !== call.sessionId)
      throw Error('Only the assistant conversation may configure heartbeats');
    return this.store.configure(
      { sessionId: old.sessionId, cwd: old.cwd },
      input.intervalMinutes === undefined ? old.intervalMs : input.intervalMinutes * 60000,
      old?.enabled ?? false,
      input.contextMode,
    );
  }
  async control(action: string, call: any) {
    this.ready();
    const old = this.store.get();
    if (!old || old.sessionId !== call.sessionId)
      throw Error('Only the assistant conversation controls heartbeats');
    const s = this.store.control(action);
    if (action === 'pause') this.coordinator.withdraw('broad');
    if (action !== 'pause') void this.tick();
    return s;
  }
  async close() {
    clearInterval(this.timer);
    clearInterval(this.heartbeat);
    // Stopping the entire feature must stop the heartbeat execution, not only its observer.
    let failure: unknown;
    try {
      if (this.activeAgent && this.owned) {
        this.store.fence();
        await this.activeAgent.cancel();
      }
    } catch (error) {
      failure = error;
    }
    this.abort.abort(Error('Initiative service stopped'));
    await Promise.allSettled([this.ticking, this.running].filter(Boolean));
    if (this.owned) this.store.release();
    if (failure) throw failure;
  }
}
