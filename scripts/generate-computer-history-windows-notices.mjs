import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const manifestPath = join(repoRoot, 'apps/desktop/native/computer-history-windows/Cargo.toml');
const outputPath = join(
  repoRoot,
  'apps/desktop/resources/licenses/computer-history-windows/THIRD_PARTY_NOTICES.txt',
);
const target = 'x86_64-pc-windows-msvc';

export function renderComputerHistoryWindowsNotices(metadata) {
  const root = metadata.resolve.root;
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const included = new Set();
  // Cargo filters target edges; follow normal and build edges, including proc macros.
  function visit(id) {
    if (included.has(id)) return;
    included.add(id);
    for (const dep of nodes.get(id).deps) {
      if (dep.dep_kinds.some(({ kind }) => kind !== 'dev')) visit(dep.pkg);
    }
  }
  visit(root);

  const packages = metadata.packages
    .filter((pkg) => pkg.id !== root && included.has(pkg.id))
    .sort((left, right) =>
      Buffer.compare(
        Buffer.from(`${left.name}@${left.version}`, 'utf8'),
        Buffer.from(`${right.name}@${right.version}`, 'utf8'),
      ),
    );
  const sections = packages.map((pkg) => {
    if (!pkg.license) throw new Error(`${pkg.name}@${pkg.version}: missing SPDX license metadata`);
    const directory = dirname(pkg.manifest_path);
    const licenseFiles = readdirSync(directory, { withFileTypes: true })
      .filter(
        (entry) => entry.isFile() && /^(licen[cs]e|copying|notice)(?:[._-].*)?$/iu.test(entry.name),
      )
      .map((entry) => entry.name)
      .sort();
    if (licenseFiles.length === 0) {
      throw new Error(`${pkg.name}@${pkg.version}: packaged crate has no license or notice text`);
    }
    const source = pkg.repository ?? pkg.homepage ?? pkg.source ?? 'unknown';
    const heading = `${pkg.name} ${pkg.version}`;
    return [
      heading,
      '-'.repeat(heading.length),
      `SPDX license: ${pkg.license}`,
      `Source: ${source}`,
      ...licenseFiles.flatMap((name) => [
        '',
        `--- ${name} ---`,
        readFileSync(join(directory, name), 'utf8').replace(/\r\n?/gu, '\n').trimEnd(),
      ]),
    ].join('\n');
  });

  return `Maka Computer History Windows Cargo dependency notices
======================================================

Generated by scripts/generate-computer-history-windows-notices.mjs from the
locked Cargo dependency graph. Do not edit this file by hand.
Includes normal and build dependencies for the target, excluding dev-only dependencies.

Manifest: ${relative(repoRoot, manifestPath).replaceAll('\\', '/')}
Target: ${target}

${sections.join('\n\n')}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const metadata = JSON.parse(
    execFileSync(
      process.env.CARGO ?? 'cargo',
      [
        'metadata',
        '--manifest-path',
        manifestPath,
        '--locked',
        '--filter-platform',
        target,
        '--format-version',
        '1',
      ],
      { cwd: repoRoot, encoding: 'utf8', timeout: 120_000, maxBuffer: 16 * 1024 * 1024 },
    ),
  );
  const output = renderComputerHistoryWindowsNotices(metadata);
  if (process.argv.includes('--check')) {
    if (readFileSync(outputPath, 'utf8') !== output) {
      throw new Error(
        'Computer History Windows notices are stale. Run node scripts/generate-computer-history-windows-notices.mjs.',
      );
    }
    console.log('[computer-history-windows-notices] OK - Cargo dependency inventory is current.');
  } else {
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, output);
    console.log(`[computer-history-windows-notices] wrote ${outputPath}`);
  }
}
