import assert from 'node:assert/strict';
import test from 'node:test';
import { planLabels } from './pr-effort.mjs';

test('mixed product changes count authored additions and deletions while excluding generated bytes', () => {
  assert.deepEqual(
    planLabels(
      [
        { filename: 'products/maka/cli/src/main.rs', additions: 70, deletions: 10 },
        { filename: 'plugins/agent/engine/tests/session.rs', additions: 25, deletions: 5 },
        { filename: 'products/maka/workbench/app/i18n.ts', additions: 5 },
        { filename: 'docs/README.md', additions: 3 },
        { filename: 'Cargo.lock', additions: 5000 },
        { filename: 'packages\\cli\\package-lock.json', additions: 5000 },
        { filename: 'products/maka/cli/THIRD_PARTY_NOTICES.txt', additions: 5000 },
        { filename: 'scripts/model-metadata/models-dev-api.snapshot.json', additions: 5000 },
        { filename: 'assets/logo.png', additions: 1 },
      ],
      ['bug'],
    ),
    {
      label: 'effort/M',
      lines: 118,
      addLabels: ['effort/M'],
      removeLabels: [],
    },
  );
});

test('label reconciliation removes obsolete tiers and becomes idempotent', () => {
  const files = [{ filename: 'app.ts', additions: 1200, deletions: 800 }];
  assert.deepEqual(planLabels(files, ['bug', 'effort/S', 'effort/M']), {
    label: 'effort/XL',
    lines: 2000,
    addLabels: ['effort/XL'],
    removeLabels: ['effort/S', 'effort/M'],
  });
  assert.deepEqual(planLabels(files, ['bug', 'effort/XL']), {
    label: 'effort/XL',
    lines: 2000,
    addLabels: [],
    removeLabels: [],
  });
});
