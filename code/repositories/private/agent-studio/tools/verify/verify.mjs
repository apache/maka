import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {initialize,request} from '../../app/offline-api.js';

const originalFetch=globalThis.fetch;
globalThis.fetch=async path=>({json:async()=>JSON.parse(await readFile(new URL('../../app'+path,import.meta.url),'utf8'))});
await initialize();
globalThis.fetch=originalFetch;
const list=async(data={})=>(await request({url:'/decision/agent-microapp/microApp/findMicroAppPage',data})).data;
const first=await list({pageNum:1,pageSize:3});
const second=await list({pageNum:2,pageSize:3});
assert.equal(first.records.length,3);
assert.notEqual(first.records[0].microAppId,second.records[0].microAppId);
const match=await list({microAppName:first.records[0].microAppName,status:first.records[0].status,runMode:first.records[0].runMode});
assert.equal(match.total,1);
assert.equal((await list({microAppName:'不存在的学习样例'})).total,0);
const copied=await request({url:'/decision/agent-microapp/microApp/copy',data:{microAppId:first.records[0].microAppId}});
assert.equal(copied.success,true);
assert.notEqual(copied.data.microAppId,first.records[0].microAppId);
assert.equal((await list()).total,first.total+1);
assert.equal((await request({url:'/decision/agent-microapp/microAppVersion/enable',data:{id:copied.data.microAppVersionId}})).success,true);
assert.equal((await list({microAppName:copied.data.microAppName})).records[0].status,1);
assert.equal((await request({url:'/decision/agent-microapp/microApp/deleteById',data:{id:copied.data.microAppId}})).success,true);
assert.equal((await list()).total,first.total);
const created=await request({url:'/decision/agent-microapp/microApp/create',data:{microAppName:'REA 学习样例',description:'仅本地内存',runMode:4,picUrl:'/assets/images/c-logo-CScNlfvD.png'}});
assert.equal(created.success,true);
assert.equal((await list({microAppName:'REA 学习样例'})).total,1);
assert.equal(created.data.status,4);
await request({url:'/decision/agent-microapp/microApp/deleteById',data:{id:created.data.microAppId}});
assert.equal((await request({url:'https://itest.clife.net/uncollected'})).success,false);
const version=await request({url:'/agent-microapp/microAppVersion/findById',data:{id:5433}});
assert.equal(version.success,true);
const graph=JSON.parse(version.data.data);
assert.equal(graph.nodes.length,3);
assert.equal(graph.edges.length,2);
const moved=structuredClone(graph);
moved.nodes[0].position.x+=100;
assert.equal((await request({url:'/agent-microapp/microAppVersion/update',data:{microAppVersionId:5433,data:JSON.stringify(moved)}})).success,true);
assert.equal(JSON.parse((await request({url:'/agent-microapp/microAppVersion/findById',data:{id:5433}})).data.data).nodes[0].position.x,moved.nodes[0].position.x);
assert.equal((await request({url:'/agent-microapp/microAppVersion/update',data:{microAppVersionId:5433,data:'{"nodes":null}'}})).success,false);
const response=await fetch('http://127.0.0.1:4173/agent/studio/app/app-manage');
