/**
 * 顶部水平导航组件
 */
export function TopNav() {
  const pathname = usePathname()
  return (
    <nav className="flex h-11 flex-wrap items-center gap-1 border-b border-border bg-background px-6">
      {navItems.map((item) => {
        const isActive = item.exact === true ? pathname === item.to : pathname.startsWith(item.to)
        return (
          <Link
            key={item.to}
            href={item.to}
            className={cn(
              'flex items-center gap-2 rounded-md px-3 py-1.5 text-sm transition-colors',
              isActive
                ? 'bg-accent font-medium text-primary'
                : 'text-muted-foreground hover:bg-accent hover:text-foreground',
            )}
          >
            {item.icon}
            <span>{item.label}</span>
          </Link>
        )
      })}
    </nav>
  )
}
