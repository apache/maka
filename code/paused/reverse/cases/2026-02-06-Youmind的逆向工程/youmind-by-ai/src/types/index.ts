// ============================================
// 核心数据类型
// ============================================

/** 用户信息 */
export interface UserInfo {
  /** 用户 ID */
  id: string;
  /** 用户名 */
  username?: string;
  /** 邮箱 */
  email?: string;
  /** 头像 URL */
  avatarUrl?: string;
  /** 是否登录 */
  isLogin: boolean;
  /** 是否在等待列表 */
  inWaitlist?: boolean;
  /** 账户是否非活跃 */
  isInactive?: boolean;
  /** API 密钥 */
  apiKey?: string;
}

/** 剪藏内容类型 */
export enum ClipType {
  /** 文本内容 */
  TEXT = 'text',
  /** 图片 */
  IMAGE = 'image',
  /** 链接 */
  LINK = 'link',
  /** 网页 */
  WEBPAGE = 'webpage',
  /** YouTube 视频 */
  YOUTUBE = 'youtube',
  /** Twitter 推文 */
  TWEET = 'tweet',
}

/** 剪藏项基础接口 */
export interface Clip {
  /** 唯一标识符 */
  id: string;
  /** 类型 */
  type: ClipType;
  /** 标题 */
  title: string;
  /** 内容 */
  content?: string;
  /** URL */
  url?: string;
  /** 截图（base64） */
  screenshot?: string;
  /** 创建时间（ISO 8601） */
  createdAt: string;
  /** 更新时间 */
  updatedAt?: string;
  /** 标签 */
  tags?: string[];
  /** 笔记 */
  notes?: string;
  /** 元数据 */
  metadata?: Record<string, unknown>;
}

// ============================================
// YouTube 相关类型
// ============================================

/** YouTube 视频信息 */
export interface YouTubeVideo {
  /** 视频 ID */
  id: string;
  /** 标题 */
  title: string;
  /** 描述 */
  description?: string;
  /** 频道名称 */
  channelName: string;
  /** 频道 ID */
  channelId: string;
  /** 时长（秒） */
  duration?: number;
  /** 视图数 */
  viewCount?: number;
  /** 缩略图 */
  thumbnails?: YouTubeThumbnail[];
  /** 发布日期 */
  publishedAt?: string;
}

/** YouTube 缩略图 */
export interface YouTubeThumbnail {
  /** 宽度 */
  width: number;
  /** 高度 */
  height: number;
  /** URL */
  url: string;
}

/** YouTube 字幕 */
export interface YouTubeSubtitle {
  /** 语言代码 */
  lang: string;
  /** 语言名称 */
  langName?: string;
  /** 自动生成 */
  autoGenerated?: boolean;
  /** 字幕内容 */
  cues: SubtitleCue[];
}

/** 字幕条目 */
export interface SubtitleCue {
  /** 开始时间（秒） */
  start: number;
  /** 结束时间（秒） */
  end: number;
  /** 文本 */
  text: string;
}

// ============================================
// Twitter 相关类型
// ============================================

/** Twitter 推文 */
export interface Tweet {
  /** 推文 ID */
  id: string;
  /** 作者信息 */
  author: TwitterAuthor;
  /** 推文内容 */
  content: string;
  /** 创建时间 */
  createdAt: string;
  /** 媒体附件 */
  media?: TwitterMedia[];
  /** 统计数据 */
  stats: TweetStats;
  /** 引用的推文 */
  quotedTweet?: Tweet;
  /** 回复的推文 */
  repliedToTweet?: Tweet;
}

/** Twitter 作者 */
export interface TwitterAuthor {
  /** 用户 ID */
  id: string;
  /** 用户名 */
  username: string;
  /** 显示名称 */
  displayName: string;
  /** 头像 URL */
  avatarUrl?: string;
  /** 是否验证 */
  verified?: boolean;
}

/** Twitter 媒体 */
export interface TwitterMedia {
  /** 媒体类型 */
  type: 'photo' | 'video' | 'gif';
  /** URL */
  url: string;
  /** 缩略图 URL */
  thumbnailUrl?: string;
  /** 宽度 */
  width?: number;
  /** 高度 */
  height?: number;
}

/** 推文统计 */
export interface TweetStats {
  /** 点赞数 */
  likes: number;
  /** 转发数 */
  retweets: number;
  /** 回复数 */
  replies: number;
  /** 查看数 */
  views: number;
}

// ============================================
// 网页剪藏类型
// ============================================

/** 网页剪藏选项 */
export interface WebpageClipOptions {
  /** 是否包含截图 */
  includeScreenshot?: boolean;
  /** 是否使用 Jina AI 抓取 */
  useJinaAI?: boolean;
  /** 是否只保存选区 */
  selectionOnly?: boolean;
  /** 选中的文本 */
  selection?: string;
}

/** 网页剪藏结果 */
export interface WebpageClipResult {
  /** 成功标志 */
  success: boolean;
  /** 剪藏数据 */
  clip?: Clip;
  /** 错误信息 */
  error?: string;
}

/** 网页内容（Jina AI 返回） */
export interface WebpageContent {
  /** 标题 */
  title: string;
  /** 内容 */
  content: string;
  /** URL */
  url: string;
  /** 作者 */
  author?: string;
  /** 发布日期 */
  datePublished?: string;
  /** 图片 */
  images?: string[];
}

// ============================================
// AI 相关类型
// ============================================

/** AI 提供商 */
export enum AIProvider {
  CLAUDE = 'claude',
  GEMINI = 'gemini',
}

/** AI 配置 */
export interface AIConfig {
  /** 提供商 */
  provider: AIProvider;
  /** API 密钥 */
  apiKey?: string;
  /** 模型 */
  model?: string;
  /** 最大令牌数 */
  maxTokens?: number;
  /** 温度 */
  temperature?: number;
}

/** AI 响应 */
export interface AIResponse {
  /** 内容 */
  content: string;
  /** 使用的令牌 */
  tokensUsed?: number;
  /** 模型 */
  model?: string;
}

// ============================================
// 存储类型
// ============================================

/** 存储键 */
export enum StorageKey {
  /** 用户信息 */
  USER_INFO = 'USER_INFO',
  /** 剪藏列表 */
  CLIPS = 'CLIPS',
  /** 设置 */
  SETTINGS = 'SETTINGS',
  /** AI 配置 */
  AI_CONFIG = 'AI_CONFIG',
}

/** 设置 */
export interface Settings {
  /** 主题 */
  theme: 'light' | 'dark' | 'system';
  /** 语言 */
  language: string;
  /** 自动剪藏 */
  autoClip?: boolean;
  /** 默认标签 */
  defaultTags?: string[];
  /** 快捷键 */
  shortcuts?: Shortcuts;
}

/** 快捷键设置 */
export interface Shortcuts {
  /** 打开 YouMind */
  openYouMind?: string;
  /** 开始捕获 */
  startCapture?: string;
  /** 保存到 YouMind */
  saveToYouMind?: string;
  /** 开始翻译 */
  startTranslate?: string;
}

// ============================================
// 消息类型
// ============================================

/** 消息类型 */
export enum MessageType {
  /** 保存内容 */
  SAVE_CONTENT = 'SAVE_CONTENT',
  /** 保存图片 */
  SAVE_IMAGE = 'SAVE_IMAGE',
  /** 保存链接 */
  SAVE_LINK = 'SAVE_LINK',
  /** 保存网页 */
  SAVE_WEBPAGE = 'SAVE_WEBPAGE',
  /** 获取 YouTube 信息 */
  GET_YOUTUBE_INFO = 'GET_YOUTUBE_INFO',
  /** 获取 YouTube 字幕 */
  GET_YOUTUBE_SUBTITLE = 'GET_YOUTUBE_SUBTITLE',
  /** 获取 Twitter 信息 */
  GET_TWEET_INFO = 'GET_TWEET_INFO',
  /** AI 分析 */
  AI_ANALYZE = 'AI_ANALYZE',
  /** Jina AI 抓取 */
  JINA_SCRAP = 'JINA_SCRAP',
  /** 打开侧边栏 */
  OPEN_SIDEBAR = 'OPEN_SIDEBAR',
}

/** 消息基础接口 */
export interface Message<T = unknown> {
  /** 消息类型 */
  type: MessageType;
  /** 数据 */
  data?: T;
  /** 消息 ID（用于响应） */
  messageId?: string;
}

